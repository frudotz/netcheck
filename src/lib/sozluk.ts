/** "{n} rapor" gibi metinlerdeki yer tutucuları doldurur. */
export function bicim(metin: string, degerler: Record<string, string | number>): string {
  return metin.replace(/\{(\w+)\}/g, (_, ad: string) => String(degerler[ad] ?? `{${ad}}`));
}

